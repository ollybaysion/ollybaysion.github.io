/**
 * 무대 상수. 값은 `~/repo/blog-screens/*.dc.html` 정본에서 그대로 읽어온 것.
 * 여기 숫자를 바꾸면 이미 박힌 좌표의 의미가 달라진다 = 전량 재측량 이벤트.
 */

/** 원장 알고리즘 버전. 배치 규칙이 바뀌면 올린다. */
export const COORDS_VERSION = 'coords-v1';

/** 빛구멍 중심 (Main.dc.html: `var CX = 350, CY = 235`). */
export const CENTER = { x: 350, y: 235 } as const;

/** 빛구멍 반지름 (Main.dc.html: `<circle ... r="95">`). */
export const LIGHT_HOLE_RADIUS = 95;

/** 나이테 반지름 범위. 안쪽 = 옛날, 바깥쪽 = 최근. */
export const RADIUS_MIN = 140;
export const RADIUS_MAX = 195;

/** 반지름 밴드 하나가 덮는 기간(년). epoch + BAND_YEARS = RADIUS_MAX. */
export const BAND_YEARS = 5;

/** 1년(ms). 그레고리력 평균 연장 365.2425일 고정 — 결정론 유지용. */
export const YEAR_MS = 365.2425 * 24 * 60 * 60 * 1000;

/**
 * 화면 거리를 %로 바꿀 때 쓰는 분모. 두 글이 벌어질 수 있는 최대 거리
 * (안쪽 테두리를 사이에 두고 정반대) = 지름.
 */
export const D_MAX = 2 * RADIUS_MAX;

/** 글 하나에서 "가까운 글"을 몇 편까지 실을지. */
export const NEIGHBOR_LIMIT = 8;

/** 같은 시리즈 보너스. 유사도에 더한 뒤 1.0에서 자른다. */
export const SERIES_BONUS = 0.3;

/** 슬러그 해시 지터 폭(±도). 같은 태그 셋을 가진 두 글을 떼어놓는 장치. */
export const JITTER_DEG = 1;

/**
 * 임베딩 버전. 모델·풀링·아래 눈금 중 하나라도 바뀌면 올린다 =
 * 벡터 전량 재측량이라는 의식적 이벤트.
 */
export const EMBED_VERSION = 'embed-v1';

/**
 * 글을 벡터로 바꾸는 모델. 고정이다 — 모델이 바뀌면 코사인의 눈금이 통째로 달라진다.
 *
 * 한국어 산문 아홉 편(닮은 쌍 7 · 안 닮은 쌍 8을 사람이 미리 표시)으로 후보를 재고
 * 골랐다(2026-08-30):
 *
 * | 모델 | 차원 | 닮은 쌍 최저 | 안 닮은 쌍 최고 | 간극 |
 * | --- | --- | --- | --- | --- |
 * | multilingual-e5-small | 384 | 0.830 | 0.847 | **-0.017** |
 * | multilingual-e5-base | 768 | 0.767 | 0.809 | **-0.041** |
 * | bge-m3 (mean 풀링) | 1024 | 0.768 | 0.750 | +0.018 |
 * | bge-m3 (cls 풀링) | 1024 | 0.462 | 0.431 | **+0.031** |
 *
 * e5 계열은 닮은 쌍과 안 닮은 쌍이 겹쳐서 어떤 문턱을 잡아도 둘을 가를 수 없었다.
 * bge-m3만 간극이 양수다 — 그리고 8192 토큰이라 긴 글도 자르지 않고 통째로 읽는다.
 */
export const EMBED_MODEL = 'Xenova/bge-m3';

/**
 * 풀링과 양자화도 눈금의 일부다 — 바꾸면 같은 글이 다른 벡터가 된다.
 * bge-m3의 정식 밀집 표현은 cls다(위 표에서 mean보다 간극도 넓다).
 */
export const EMBED_POOLING = 'cls';
export const EMBED_DTYPE = 'q8';

/** bge-m3가 뱉는 벡터 길이. 원장을 읽을 때 검산에 쓴다. */
export const VECTOR_DIMS = 1024;

/** 벡터를 원장에 적을 때의 소수 자릿수. 코사인은 이 자릿수에서 이미 다섯 자리까지 같다. */
export const VECTOR_PRECISION = 6;

/**
 * 코사인 바닥 — 이보다 안 닮았으면 유사도 0.
 *
 * 임베딩의 원시 코사인은 **0에서 시작하지 않는다.** 한국어 산문끼리는 아무 상관이 없어도
 * 0.30~0.43이 나온다(측정: 커피↔여행 0.381 · 커피↔음식 0.423 · 한국어↔영어 0.333,
 * 사람이 "안 닮았다"고 표시한 여덟 쌍의 최고 0.431). 이 값을 그대로 유사도로 쓰면
 * **모든 글이 서로 어지간히 닮은 셈**이 되어 `placeAngle`의 가중 평균이 카테고리
 * 한가운데로 뭉친다. 그래서 바닥을 빼고 다시 편다.
 *
 * 값은 닮은 쌍 최저(0.462)와 안 닮은 쌍 최고(0.431) 사이의 빈 구간에 놓았다.
 */
export const VECTOR_FLOOR = 0.44;

/**
 * 코사인 천장 — 이보다 닮았으면 유사도 1.
 *
 * 서로 다른 글이 현실에서 닿는 꼭대기에 맞췄다(측정: 같은 시리즈 다음 화 0.800).
 * 더 위는 사실상 같은 글이다 — 재서술 0.930 · 자기 자신 1.000.
 */
export const VECTOR_CEIL = 0.8;

/** 글 하나에 실을 "다른 자리에서 닮은 글" 최대 편수. 정본 꼬리가 그만큼을 받는다. */
export const DISCOVERY_LIMIT = 3;

/**
 * 발견 레이어의 문턱. 가까운 글과 달리 **화면 거리가 먼데도** 데려오는 자리라,
 * 어중간하게 닮은 글까지 올리면 계약("가까우면 닮았다")이 흐려진다. 확실할 때만 잇는다.
 * 0.35 = 원시 코사인 0.566 — 위 아홉 편에서는 커피와 개발에 양다리를 걸친 글 하나만 넘었다.
 */
export const DISCOVERY_FLOOR = 0.35;
